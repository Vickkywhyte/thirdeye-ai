function riskColor(score: number | null): string {
  if (score === null) return '#6B7280'
  if (score >= 80) return '#DC2626'
  if (score >= 60) return '#F97316'
  if (score >= 40) return '#EAB308'
  return '#22C55E'
}

function riskLabel(score: number | null): string {
  if (score === null) return 'Not Scored'
  if (score >= 80) return 'CRITICAL'
  if (score >= 60) return 'HIGH'
  if (score >= 40) return 'MEDIUM'
  return 'LOW'
}

function severityLabel(hitCount: number): string {
  if (hitCount === 0) return 'Clear'
  if (hitCount >= 5) return 'High'
  if (hitCount >= 2) return 'Medium'
  return 'Low'
}

function templateTitle(template: ReportTemplate): string {
  switch (template) {
    case 'standard_dd': return 'Due Diligence Report'
    case 'enhanced_dd': return 'Enhanced Due Diligence Report'
    case 'sanctions_alert': return 'Screening Summary Report'
    case 'periodic_review': return 'Periodic Review Report'
  }
}

function formatDate(iso: string): string {
  return new Date(iso).toLocaleDateString('en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  })
}

function CoverPage({ data, template }: { data: ReportData; template: ReportTemplate }) {
  return (
    <Page size="A4" style={styles.coverPage}>
      <Text style={styles.logo}>ThirdEye AI</Text>
      <Text style={styles.logoSub}>Third-Party Due Diligence Platform</Text>
      <Text style={styles.coverTitle}>{templateTitle(template)}</Text>
      <Text style={styles.coverEntity}>{data.entity.name}</Text>
      <Text style={styles.classification}>CONFIDENTIAL</Text>
      <Text style={styles.coverMeta}>Date: {formatDate(data.generatedAt)}</Text>
      <Text style={styles.coverMeta}>Generated by: {data.generatedBy}</Text>
      <Text style={styles.coverMeta}>
        Risk Score: {data.investigation.risk_score ?? 'N/A'} — {riskLabel(data.investigation.risk_score)}
      </Text>
    </Page>
  )
}

function ScreeningTable({ results }: { results: ScreeningResultData[] }) {
  return (
    <View>
      <View style={styles.tableHeader}>
        <Text style={styles.tableCellHeader}>Type</Text>
        <Text style={styles.tableCellHeader}>Status</Text>
        <Text style={styles.tableCellHeader}>Hits</Text>
        <Text style={styles.tableCellHeader}>Severity</Text>
      </View>
      {results.map((r) => (
        <View key={r.id} style={styles.tableRow}>
          <Text style={styles.tableCell}>{r.type.replace('_', ' ').toUpperCase()}</Text>
          <Text style={styles.tableCell}>{r.status}</Text>
          <Text style={styles.tableCell}>{r.hit_count}</Text>
          <Text style={styles.tableCell}>{severityLabel(r.hit_count)}</Text>
        </View>
      ))}
    </View>
  )
}

function ReportDocument({ data, template }: { data: ReportData; template: ReportTemplate }) {
  const score = data.investigation.risk_score

  return (
    <Document
      title={`${templateTitle(template)} — ${data.entity.name}`}
      author="ThirdEye AI"
      subject="Due Diligence Report"
      creator="ThirdEye AI Platform"
    >
      <CoverPage data={data} template={template} />

      <Page size="A4" style={styles.page}>
        <Text style={styles.sectionTitle}>1. Executive Summary</Text>
        {data.aiAnalysis ? (
          <Text style={styles.paragraph}>{data.aiAnalysis.summary}</Text>
        ) : (
          <Text style={styles.paragraph}>
            This report presents the findings of a {templateTitle(template).toLowerCase()} conducted
            on {data.entity.name} ({data.entity.type}), jurisdicted in{' '}
            {data.entity.jurisdiction ?? 'an unspecified jurisdiction'}. The investigation was
            initiated on {formatDate(data.investigation.created_at)} and the entity received a risk
            score of {score ?? 'N/A'} ({riskLabel(score)}).
          </Text>
        )}

        <Text style={styles.sectionTitle}>2. Risk Score Summary</Text>
        <Text style={styles.paragraph}>
          Overall Risk Score: {score ?? 'N/A'} / 100
        </Text>
        <Text style={{ ...styles.riskBadge, color: riskColor(score) }}>
          Risk Level: {riskLabel(score)}
        </Text>

        <Text style={styles.sectionTitle}>3. Screening Results</Text>
        {data.screeningResults.length > 0 ? (
          <ScreeningTable results={data.screeningResults} />
        ) : (
          <Text style={styles.paragraph}>No screening results available.</Text>
        )}

        <View style={styles.footer} fixed>
          <Text>Generated by ThirdEye AI · Confidential</Text>
          <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
        </View>
      </Page>

      {(data.aiAnalysis || data.analystNotes.length > 0) && (
        <Page size="A4" style={styles.page}>
          {data.aiAnalysis && (
            <>
              <Text style={styles.sectionTitle}>4. Key Findings</Text>
              {data.aiAnalysis.keyFindings.map((f, i) => (
                <Text key={i} style={styles.listItem}>• {f}</Text>
              ))}

              <Text style={styles.sectionTitle}>5. Recommended Actions</Text>
              {data.aiAnalysis.recommendedActions.map((a, i) => (
                <Text key={i} style={styles.listItem}>{i + 1}. {a}</Text>
              ))}
            </>
          )}

          {data.analystNotes.length > 0 && (
            <>
              <Text style={styles.sectionTitle}>
                {data.aiAnalysis ? '6' : '4'}. Analyst Notes
              </Text>
              {data.analystNotes.map((n) => (
                <View key={n.id} style={styles.timelineEntry}>
                  <Text style={styles.paragraph}>{n.content}</Text>
                  <Text style={styles.timelineDate}>
                    {n.author_name ?? 'Analyst'} — {formatDate(n.created_at)}
                  </Text>
                </View>
              ))}
            </>
          )}

          <View style={styles.footer} fixed>
            <Text>Generated by ThirdEye AI · Confidential</Text>
            <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
          </View>
        </Page>
      )}

      {data.timelineEvents.length > 0 && (
        <Page size="A4" style={styles.page}>
          <Text style={styles.sectionTitle}>Appendix: Timeline</Text>
          {data.timelineEvents.map((e) => (
            <View key={e.id} style={styles.timelineEntry}>
              <Text style={styles.timelineTitle}>{e.title}</Text>
              {e.description && (
                <Text style={styles.paragraph}>{e.description}</Text>
              )}
              <Text style={styles.timelineDate}>{formatDate(e.created_at)}</Text>
            </View>
          ))}

          <View style={styles.footer} fixed>
            <Text>Generated by ThirdEye AI · Confidential</Text>
            <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
          </View>
        </Page>
      )}
    </Document>
  )
}

export async function generatePDF(
  reportData: ReportData,
  template: ReportTemplate
): Promise<Buffer> {
  logger.info('Generating PDF', { template, entity: reportData.entity.name })
  return measureAsync('pdf.render', () =>
    renderToBuffer(<ReportDocument data={reportData} template={template} />)
  )
}
